function renderSocialInputRow({
  rows,
  index,
  displayIndex,
  onDelete,
  onChange,
  options,
  onDragStart,
  onDragEnter,
  onDragOver,
  onDrop,
  onDragEnd,
  onPointerDown,
  onPointerMove,
  onPointerUp,
  onPointerCancel,
  isDropTarget
}) {
  const row = rows[index]
  const nameLabel = `Social Account Name ${displayIndex + 1}`
  const homepageLabel = `Social Account Homepage ${displayIndex + 1}`

  const handleTextInput = (field) => (event) => {
    const target = event.target
    const nextValue = field === 'homepage'
      ? sanitizeUrlFieldValue(target.value)
      : sanitizeSocialFieldValue(target.value)
    if (rows[index]) {
      applyRowFieldChange(rows[index], field, nextValue, rowHasContent)
      onChange()
    }
  }

  const handleAccountTypeInput = (event) => {
    const comboboxEvent = event
    if (!comboboxEvent.detail.option) return
    const selected = findSocialAccountOption(options, String(comboboxEvent.detail.option.value))
    if (!rows[index]) return

    if (!selected) {
      applyRowFieldChange(rows[index], 'name', '', rowHasContent)
      applyRowFieldChange(rows[index], 'icon', '', rowHasContent)
      onChange()
      return
    }

    applyRowFieldChange(rows[index], 'name', selected.label, rowHasContent)
    applyRowFieldChange(rows[index], 'icon', selected.icon || DEFAULT_ICON_URI, rowHasContent)

    onChange()
  }

  const handleDelete = (event) => {
    event.preventDefault()
    onDelete()
  }

  return html`
    <div
      class="profile-edit-dialog__row profile-edit-dialog__row--social ${isDropTarget ? 'profile-edit-dialog__row--drop-target' : ''}"
      data-social-reorder-index=${String(index)}
      @dragenter=${() => onDragEnter(index)}
      @dragover=${(event) => onDragOver(event, index)}
      @drop=${(event) => onDrop(event, index)}
    >
      <solid-ui-button
        class="profile-edit-dialog__drag-handle"
        variant="ghost"
        aria-label=${`Reorder social account ${displayIndex + 1}`}
        title="Drag to reorder"
        draggable="true"
        @dragstart=${(event) => onDragStart(event, index)}
        @dragend=${() => onDragEnd()}
        @pointerdown=${(event) => onPointerDown(event, index)}
        @pointermove=${(event) => onPointerMove(event)}
        @pointerup=${(event) => onPointerUp(event)}
        @pointercancel=${(event) => onPointerCancel(event)}
      >
        <span slot="icon" aria-hidden="true">${bentoIcon}</span>
      </solid-ui-button>
      <img
        class="profile-edit-dialog__social-icon"
        src="${row?.icon || DEFAULT_ICON_URI}"
        alt="${row?.name || 'Social'} icon"
        width="30"
        height="30"
        loading="lazy"
      />
      <label aria-label=${nameLabel} class="label profile-edit-dialog__field profile-edit-dialog__field--social-type">
        ${renderSocialAccountInputSelect(row, index, options, handleAccountTypeInput)}
      </label>
      <label aria-label=${homepageLabel} class="label profile-edit-dialog__field profile-edit-dialog__field--social-url">
        <input
          class="input"
          type="text"
          name=${`social-homepage-${index}`}
          .value=${row?.homepage || ''}
          data-contact-field="homepage"
          data-entry-node=${row?.entryNode || ''}
          data-row-status=${row?.status || 'n/a'}
          placeholder="Profile link or handle"
          autocomplete="off"
          inputmode="text"
          required
          @input=${handleTextInput('homepage')}
        />
          <small class="profile-edit-dialog__input-help-text">Enter your profile link, handle, or username.</small>
      </label>
      <div class="profile-edit-dialog__actions profile-edit-dialog__actions--edge">
        <solid-ui-button
          variant="ghost"
          aria-label=${`Delete social account ${displayIndex + 1}`}
          title=${deleteEntryButtonTitleText}
          @click=${handleDelete}
        >
          <span slot="icon" aria-hidden="true">${trashIcon}</span>
        </solid-ui-button>
      </div>
    </div>
  `
}

function renderSocialSection(rows, options, onRerender) {
  let dragSourceIndex = null
  let dropTargetIndex = null
  let touchPointerId = null

  const reorderRows = (from, to) => {
    if (from === to) return
    const row = rows[from]
    if (!row) return
    rows.splice(from, 1)
    rows.splice(to, 0, row)
  }

  const handleDragStart = (event, index) => {
    dragSourceIndex = index
    dropTargetIndex = index

    if (event.dataTransfer) {
      event.dataTransfer.effectAllowed = 'move'
      event.dataTransfer.setData('text/plain', String(index))
    }
  }

  const handleDragEnter = (index) => {
    if (dragSourceIndex === null) return
    dropTargetIndex = index
  }

  const handleDragOver = (event, index) => {
    event.preventDefault()
    if (dragSourceIndex !== null) {
      dropTargetIndex = index
    }
    if (event.dataTransfer) {
      event.dataTransfer.dropEffect = 'move'
    }
  }

  const handleDrop = (event, index) => {
    event.preventDefault()
    const transferIndex = event.dataTransfer?.getData('text/plain')
    const sourceIndex = dragSourceIndex ?? (transferIndex ? Number(transferIndex) : null)
    if (sourceIndex === null || Number.isNaN(sourceIndex)) return
    reorderRows(sourceIndex, index)
    dragSourceIndex = null
    dropTargetIndex = null
    onRerender()
  }

  const handleDragEnd = () => {
    dragSourceIndex = null
    dropTargetIndex = null
  }

  const updateTouchDropTarget = (event) => {
    const dom = (event.currentTarget)?.ownerDocument || document
    const target = (dom.elementFromPoint(event.clientX, event.clientY))
      ?.closest('[data-social-reorder-index]')
    if (!target) return

    const nextIndex = Number(target.dataset.socialReorderIndex)
    if (!Number.isNaN(nextIndex)) {
      dropTargetIndex = nextIndex
    }
  }

  const handlePointerDown = (event, index) => {
    if (event.pointerType !== 'touch') return

    event.preventDefault()
    dragSourceIndex = index
    dropTargetIndex = index
    touchPointerId = event.pointerId
    ;(event.currentTarget)?.setPointerCapture?.(event.pointerId)
  }

  const handlePointerMove = (event) => {
    if (event.pointerType !== 'touch' || touchPointerId !== event.pointerId || dragSourceIndex === null) return

    event.preventDefault()
    updateTouchDropTarget(event)
  }

  const handlePointerUp = (event) => {
    if (event.pointerType !== 'touch' || touchPointerId !== event.pointerId) return

    event.preventDefault()
    updateTouchDropTarget(event)
    const sourceIndex = dragSourceIndex
    const targetIndex = dropTargetIndex
    ;(event.currentTarget)?.releasePointerCapture?.(event.pointerId)
    touchPointerId = null
    dragSourceIndex = null
    dropTargetIndex = null

    if (sourceIndex === null || targetIndex === null || sourceIndex === targetIndex) return

    reorderRows(sourceIndex, targetIndex)
    onRerender()
  }

  const handlePointerCancel = (event) => {
    if (event.pointerType !== 'touch' || touchPointerId !== event.pointerId) return

    ;(event.currentTarget)?.releasePointerCapture?.(event.pointerId)
    touchPointerId = null
    dragSourceIndex = null
    dropTargetIndex = null
  }

  const visibleRows = rows
    .map((row, index) => ({ row, index }))
    .filter(({ row }) => row.status !== 'deleted')

  return html`
    <section class="profile-edit-dialog__section" aria-label="Social Accounts">
      <fieldset>
        <legend class="sr-only">Social account entries</legend>
        ${visibleRows.map(({ index }, displayIndex) =>
          renderSocialInputRow({
            rows,
            index,
            displayIndex,
            onDelete: () => {
              deleteRow(rows, index)
              onRerender()
            },
            onChange: onRerender,
            options,
            onDragStart: handleDragStart,
            onDragEnter: handleDragEnter,
            onDragOver: handleDragOver,
            onDrop: handleDrop,
            onDragEnd: handleDragEnd,
            onPointerDown: handlePointerDown,
            onPointerMove: handlePointerMove,
            onPointerUp: handlePointerUp,
            onPointerCancel: handlePointerCancel,
            isDropTarget: dropTargetIndex === index
          })
        )}
      </fieldset>
    </section>
  `
}

function renderSocialEditTemplate(
  form,
  formState,
  store,
  viewerMode,
  rerenderOptions = {}
) {
  const rerender = (nextOptions = {}) => renderSocialEditTemplate(form, formState, store, viewerMode, nextOptions)
  const socialOptions = getSocialAccountOptions(store)
  render(html`
    ${renderSocialSection(formState.socialAccounts, socialOptions, rerender)}
    ${viewerMode !== 'owner'
      ? html`<p class="profile-edit-dialog__login-message">${ownerLoginRequiredDialogMessageText}</p>`
      : null}
  `, form)

  if (rerenderOptions.focusSelector) {
    focusSocialField(form, rerenderOptions.focusSelector)
  }
}

function createSocialEditForm(details, store, viewerMode) {
  const form = document.createElement('form')
  form.classList.add('profile__edit-form')

  const formState = toFormState(details)
  formState.initialExistingOrder = formState.socialAccounts
    .filter((row) => Boolean((row.entryNode || '').trim()))
    .map((row) => (row.entryNode || '').trim())
  renderSocialEditTemplate(form, formState, store, viewerMode)

  const addRow = () => {
    formState.socialAccounts.unshift({
      name: '',
      icon: '',
      homepage: '',
      entryNode: '',
      status: 'new'
    })
    renderSocialEditTemplate(form, formState, store, viewerMode, { focusSelector: '[name="social-account-type-0"]' })
  }

  return { form, formState, addRow }
}

export async function createSocialEditDialog(
  event,
  store,
  subject,
  socialAccounts,
  viewerMode,
  onSaved
) {
  const dom = (event.currentTarget)?.ownerDocument || document
  const { form, formState, addRow } = createSocialEditForm(socialAccounts, store, viewerMode)

  const result = await openInputDialog({
    title: editSocialDialogTitleText,
    dom,
    form,
    onOpen: () => focusSocialField(form, getInitialSocialFocusSelector(formState.socialAccounts)),
    shouldCloseWithoutSave: () => {
      const ops = summarizeRowOps(formState.socialAccounts, rowHasContent)
      const orderChanged = hasOrderChanged(formState.socialAccounts, formState.initialExistingOrder)
      return ops.create.length === 0 && ops.update.length === 0 && ops.remove.length === 0 && !orderChanged
    },
    headerAction: {
      type: 'button',
      label: '+ Add More',
      ariaLabel: 'Add another social account',
      onClick: addRow
    },
    submitLabel: dialogSubmitLabelText,
    cancelLabel: dialogCancelLabelText,
    validate: () => {
      if (viewerMode !== 'owner') {
        return ownerLoginRequiredDialogMessageText
      }
      return validateSocialBeforeSave(formState.socialAccounts)
    },
    onSave: async () => {
      const socialOps = summarizeRowOps(formState.socialAccounts, rowHasContent)
      const plan = {
        create: socialOps.create,
        update: socialOps.update,
        remove: socialOps.remove
      }
      await processSocialMutations(store, subject, plan, formState.socialAccounts)
    },
    formatSaveError: (error) => {
      return error instanceof Error ? error.message : saveSocialUpdatesFailedMessageText
    }
  })

  if (!result) return

  if (onSaved) {
    await onSaved()
  }
}
