function isWorkTypeTerm(term) {
  const value = termValue(term).trim().toLowerCase()
  if (!value) return false
  return value === 'work' || value.endsWith('#work') || value.endsWith('/work')
}

function hasWorkType(store, entryNode, doc) {
  if ((entryNode).termType !== 'NamedNode') return false
  const inDocStatements = store.statementsMatching(entryNode, ns.rdf('type'), null, doc)
  const anyGraphStatements = store.statementsMatching(entryNode, ns.rdf('type'))

  return [...inDocStatements, ...anyGraphStatements].some((statement) =>
    isWorkTypeTerm(statement.object)
  )
}

function selectPrimaryPoint(
  store,
  subject,
  predicate,
  doc,
  kind,
  fallbackType
) {
  const inDocStatements = store.statementsMatching(subject, predicate, null, doc)
  const anyGraphStatements = store.statementsMatching(subject, predicate)
  const nodes = [...inDocStatements, ...anyGraphStatements].map((statement) => statement.object)
  const candidates = []

  const seen = new Set()
  for (const entryNode of nodes) {
    const key = termValue(entryNode)
    if (key && seen.has(key)) continue
    if (key) seen.add(key)

    const valueNode = resolvePointValueNode(store, entryNode, doc, kind)
    if (!valueNode) continue

    const type = resolvePointType(store, entryNode, doc) || fallbackType
    candidates.push({ entryNode, type, valueNode })
  }

  const workCandidate = candidates.find((candidate) =>
    hasWorkType(store, candidate.entryNode, doc) || isWorkTypeTerm(candidate.type)
  )
  if (workCandidate) return workCandidate

  if (candidates.length > 0) return candidates[0]

  return undefined
}

export function pronounsAsText (store, subject) {
  let pronouns = store.anyJS(subject, ns.solid('preferredSubjectPronoun')) || ''
  if (pronouns) {
    const them = store.anyJS(subject, ns.solid('preferredObjectPronoun'))
    if (them) {
      pronouns += '/' + them
    }
  }
  return pronouns || ''
}

function formatLocation(countryName, locality) {
  return countryName && locality
    ? `${locality}, ${countryName}`
    : countryName || locality || null
}

function normalizeRoleType(value) {
  return (value || '').replace(/\s+/g, '').toLowerCase()
}

function selectHeadingRole(roles) {
  const currentRole = roles.find((role) => role.isCurrentRole || normalizeRoleType(role.roleType) === 'currentrole')
  if (currentRole) return currentRole

  return roles.find((role) => {
    const normalizedRoleType = normalizeRoleType(role.roleType)
    return normalizedRoleType !== 'currentrole' && normalizedRoleType !== 'futurerole'
  })
}

export const presentProfile = (
  subject,
  store
) => {
  const name = utils.label(subject)
  // on contact-pane form it is foaf, but maybe another app saves with vcard.
  const nickname = store.anyValue(subject, ns.vcard('nickname')) || store.anyValue(subject, ns.foaf('nick')) || undefined
  const dateOfBirth = store.anyValue(subject, ns.vcard('bday')) || undefined
  const imageSrc = widgets.findImage(subject)
  const headingRole = selectHeadingRole(presentCV(subject, store))
  const jobTitle = headingRole?.title || undefined
  const doc = subject.doc()

  // Contact info - we will only show one of each type here
  // Just doing for now, but we should change to either store a primary
  // indicator or store it a bit differently in the store.
  const primaryPhone = selectPrimaryPoint(store, subject, ns.vcard('hasTelephone'), doc, 'phone', ns.vcard('Voice'))

  const primaryEmail = selectPrimaryPoint(store, subject, ns.vcard('hasEmail'), doc, 'email', ns.vcard('Internet'))

  const primaryAddressEntryNode = store.any(subject, ns.vcard('hasAddress')) || undefined
  const primaryAddressType = primaryAddressEntryNode
    ? (store.any(primaryAddressEntryNode, ns.rdf('type')) || undefined)
    : undefined
  const primaryStreetAddress = primaryAddressEntryNode
    ? (store.anyValue(primaryAddressEntryNode, ns.vcard('street-address')) || undefined)
    : undefined
  const primaryLocality = primaryAddressEntryNode
    ? (store.anyValue(primaryAddressEntryNode, ns.vcard('locality')) || undefined)
    : undefined
  const primaryRegion = primaryAddressEntryNode
    ? (store.anyValue(primaryAddressEntryNode, ns.vcard('region')) || undefined)
    : undefined
  const primaryPostalCode = primaryAddressEntryNode
    ? (store.anyValue(primaryAddressEntryNode, ns.vcard('postal-code')) || undefined)
    : undefined
  const primaryCountryName = primaryAddressEntryNode
    ? (store.anyValue(primaryAddressEntryNode, ns.vcard('country-name')) || undefined)
    : undefined
  const primaryAddress = primaryAddressEntryNode
    ? {
      entryNode: primaryAddressEntryNode,
      type: primaryAddressType,
      streetAddress: primaryStreetAddress,
      locality: primaryLocality,
      region: primaryRegion,
      postalCode: primaryPostalCode,
      countryName: primaryCountryName
    }
    : undefined

  const address = primaryAddressEntryNode || null
  const countryName =
    address != null
      ? store.anyValue(address, ns.vcard('country-name'))
      : null
  const locality =
    address != null
      ? store.anyValue(address, ns.vcard('locality'))
      : null

  const pronouns = pronounsAsText(store, subject)

  return {
    name,
    nickname,
    imageSrc,
    dateOfBirth,
    jobTitle,
    primaryPhone,
    primaryEmail,
    primaryAddress,
    location: formatLocation(countryName, locality),
    pronouns,
    entryNode: subject
  }
}
