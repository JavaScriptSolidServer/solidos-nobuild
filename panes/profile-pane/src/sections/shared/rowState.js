export function applyRowFieldChange(
  row,
  field,
  nextValue,
  hasContent
) {
  row[field] = nextValue

  if (!hasContent(row)) {
    row.status = row.entryNode ? 'deleted' : 'new'
    return
  }

  if (row.entryNode) {
    row.status = row.status === 'existing' || row.status === 'deleted' ? 'modified' : row.status
    return
  }

  row.status = 'new'
}
